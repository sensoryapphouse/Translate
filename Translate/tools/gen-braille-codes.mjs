// Generate the braille-code list FROM THE TABLES THAT ACTUALLY SHIP.
//
// The first version of this list was ten entries typed by hand, and PB asked the
// obvious question: where is Welsh? It was there all along — cy-cy-g1.utb and
// cy-cy-g2.ctb — along with 125 language prefixes across 264 tables. A
// hand-curated list is a measurement that goes stale the moment liblouis is
// updated, and it silently answers "no" for every language its author forgot.
//
// So the list is DERIVED. Run this after any liblouis update:
//     node "Translate/tools/gen-braille-codes.mjs"
//
// WHAT IT DOES NOT DO: invent display names. Intl.DisplayNames turns 'cy' into
// "Welsh" in the user's own language at runtime, which is both more correct and
// less to maintain than a hand-written name table — and it means a French user
// sees "gallois" without anyone translating anything.
//
// WHAT IT SKIPS, and why. Computer-braille (comp8) tables are 8-dot codes for
// programming, not literary reading; the transliteration tables (cuneiform,
// Akkadian, ancient languages) are scholarly tools; and IPA is phonetic
// notation. None belongs in a picker offered to a child, and including them
// would bury the school languages under noise.

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const TABLES = join(HERE, '../../liblouis/tables');
const OUT = join(HERE, '../braille-codes.mjs');

// Which of these already travel in the service worker: those work offline the
// moment they are chosen. Everything else needs the network the first time, and
// the picker says so rather than failing quietly on a train.
const SHIPPED = new Set(
  (readFileSync(join(HERE, '../sw.js'), 'utf8').match(/\/liblouis\/tables\/([^']+)/g) || [])
    .map((s) => s.split('/').pop()),
);

const SKIP = /comp8|cuneiform|akk|ancient-languages|borger|IPA|boxes|unicode-braille|\.tbl$|chardefs|-chardefs|\.cti$|\.uti$|\.dis$/i;

// Grade is part of the CODE, not a separate switch — a braille reader names
// "UEB grade 2" as one thing, and eBraille's own registry writes it that way.
function gradeOf(file) {
  const f = file.toLowerCase();
  if (/-g0|comp6|-comp\b/.test(f)) return { n: 1, label: 'uncontracted' };
  if (/-g1/.test(f)) return { n: 1, label: 'grade 1 (uncontracted)' };
  if (/-g2/.test(f)) return { n: 2, label: 'grade 2 (contracted)' };
  if (/-g3/.test(f)) return { n: 3, label: 'grade 3' };
  return { n: 1, label: '' };
}

const rows = [];
for (const file of readdirSync(TABLES).sort()) {
  if (!/\.(ctb|utb)$/i.test(file) || SKIP.test(file)) continue;
  const m = file.match(/^([A-Za-z]{2,3})(?:[-_]([A-Za-z]{2,4}))?/);
  if (!m) continue;
  const lang = m[1].toLowerCase();
  if (lang.length > 3) continue;
  const g = gradeOf(file);
  rows.push({
    id: file.replace(/\.(ctb|utb)$/i, ''),
    lang,
    region: (m[2] || '').toLowerCase(),
    grade: g.label,
    gradeN: g.n,
    file,
    shipped: SHIPPED.has(file),
  });
}

// One entry per language+grade: where a language has several tables of the same
// grade, prefer a SHIPPED one, then the shortest name (which is almost always
// the general table rather than a regional or specialised variant).
const best = new Map();
for (const r of rows) {
  const key = `${r.lang}:${r.gradeN}`;
  const cur = best.get(key);
  if (!cur || (r.shipped && !cur.shipped) || (r.shipped === cur.shipped && r.file.length < cur.file.length)) {
    best.set(key, r);
  }
}

const out = [...best.values()].sort((a, b) => a.lang.localeCompare(b.lang) || a.gradeN - b.gradeN);
const body = out.map((r) =>
  `  { id: ${JSON.stringify(r.id)}, lang: ${JSON.stringify(r.lang)}, grade: ${JSON.stringify(r.grade)},\n` +
  `    table: ${JSON.stringify('/tables/unicode.dis,/tables/' + r.file)}, shipped: ${r.shipped} },`
).join('\n');

writeFileSync(OUT, `// GENERATED by tools/gen-braille-codes.mjs — do not edit by hand.
// Derived from the liblouis tables that ship in this repository, so a liblouis
// update changes this file rather than leaving a hand-written list quietly
// wrong. Language NAMES are not stored: Intl.DisplayNames produces them at
// runtime, in the user's own language.
//
// ${out.length} codes across ${new Set(out.map((r) => r.lang)).size} languages;
// ${out.filter((r) => r.shipped).length} of them travel in the service worker and so work offline.
export const CODES = [
${body}
];
`, 'utf8');

console.log(`${out.length} codes, ${new Set(out.map((r) => r.lang)).size} languages, ${out.filter((r) => r.shipped).length} shipped offline`);
console.log('Welsh present:', out.some((r) => r.lang === 'cy'), '|', out.filter((r) => r.lang === 'cy').map((r) => r.id).join(', '));
