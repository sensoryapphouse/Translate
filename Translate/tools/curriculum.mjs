// How well would this work for a child of a given age?
//
// The MathCAT corpora are authentic but they are not a school. Their Nemeth half
// comes from a UNIVERSITY abstract-algebra textbook and a chemistry spec, so a
// global accuracy figure says little about a Year 6 pupil doing fractions.
//
// This benchmark is age-stratified against the England/Wales curriculum. Each
// expression is written as LaTeX (what a teacher would recognise), then put
// through the full loop with the ORIGINAL as ground truth:
//
//     LaTeX -> MathML (Temml) -> braille (MathCAT) -> our parser -> LaTeX'
//
// and judged three ways:
//   readable    we parsed it with no warnings
//   consistent  our reading forward-translates back to the SAME braille — so it
//               is a correct reading of what was written, not merely silent
//   faithful    the content of LaTeX' matches the original expression
//
// "consistent" is the one to trust: it needs no judgement about encoding, and a
// wrong structure cannot survive it.
//
// The braille is produced by MathCAT, the same authority that produced the other
// corpora, so it is what a correctly-taught child would be expected to write.
//
// Run: node connector/tools/curriculum.mjs [--failures] [--code UEB|Nemeth]

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { sourceTokens, faithfulness, latexTokens } from './lib/score.mjs';
import { loadTemml, toMathML } from './lib/structure.mjs';
import { pickReaders } from './lib/readers.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
// the readers under test: the app's hybrid decision unless MATHS_IMPL says otherwise
const readers = await pickReaders();
const uebMathsToLatex = readers.ueb;
const nemeth = readers.nemeth;
const mathcat = require(path.resolve(__dirname, '../../engine/mathcat/pkg-nodejs/emboss_mathcat.js'));
const temml = loadTemml(path.resolve(__dirname, '../../web/vendor/temml.min.js'));

// Roughly by school stage in England and Wales. The point is not a perfect
// mapping to a syllabus — it is that a Year 6 pupil and a sixth-former write
// very different things, and one accuracy figure hides that completely.
const CURRICULUM = [
  ['age 7 — KS1 / lower KS2', [
    '3+4=7', '12-5=7', '6\\times 7=42', '20\\div 4=5',
    '£2.50', '15+27=42', '100-38=62', '9\\times 8=72',
    '\\frac{1}{2}', '\\frac{1}{4}', '2+3+4=9', '7\\times 3=21',
  ]],
  ['age 11 — upper KS2 / Year 6', [
    '\\frac{1}{2}+\\frac{1}{3}=\\frac{5}{6}', '\\frac{3}{4}\\times 8=6',
    '0.75=\\frac{3}{4}', '25\\%=\\frac{1}{4}', '3.6\\div 0.4=9',
    '-7+3=-4', '2+3\\times 4=14', '(8-3)\\times 2=10',
    '12.75\\times 4=51', '\\frac{2}{5}=0.4', '5^{2}=25', '1750\\text{ cm}=17.5\\text{ m}',
  ]],
  ['age 14 — KS3', [
    '3x+2=11', 'x^{3}-2x^{2}+1', '2(x+3)=14', 'y=mx+c',
    'a^{2}+b^{2}=c^{2}', '\\frac{x+1}{x-1}', 'x^{-1}', '3x+2y=12',
    '(a+b)^{2}', 'x^{2}-9=(x+3)(x-3)', '\\sqrt{49}=7', '2^{10}=1024',
  ]],
  ['age 16 — GCSE', [
    'x=\\frac{-b\\pm\\sqrt{b^{2}-4ac}}{2a}', '6.02\\times 10^{23}',
    '\\sin 30^{\\circ}=\\frac{1}{2}', '\\tan\\theta=\\frac{o}{a}',
    'A=\\pi r^{2}', '\\sqrt{50}=5\\sqrt{2}', 'x^{\\frac{1}{2}}',
    '\\frac{3x+1}{2}=5', '0<x\\le 10', 'x\\neq 0',
    'P(A)=\\frac{3}{8}', '\\sqrt[3]{27}=3',
  ]],
  ['age 18 — A-level', [
    '\\frac{dy}{dx}=2x', '\\int_{0}^{1}x^{2}dx=\\frac{1}{3}',
    '\\log_{10}(100)=2', '\\ln e=1', '\\sum_{n=1}^{10}n=55',
    '\\lim_{x\\to 0}\\frac{\\sin x}{x}=1', 'e^{i\\pi}+1=0',
    '\\frac{d}{dx}(x^{3})=3x^{2}', '\\binom{n}{r}', 'f(x)=x^{2}+3x-4',
    '\\sqrt{-1}=i', '\\cos^{2}\\theta+\\sin^{2}\\theta=1',
  ]],
];

// An INDEPENDENT set, generated by 25 separate agents across the curriculum
// strands and five deliberately awkward themes, none of them chosen by whoever
// was fixing the parser. The hand-written stages above are useful for seeing
// WHERE a problem lies; this one is the honest score, because passing it cannot
// be arranged by editing the test.
const GENERATED = (() => {
  try {
    return JSON.parse(fs.readFileSync(path.join(__dirname, 'corpus', 'curriculum-generated.json'), 'utf8'));
  } catch { return []; }
})();

const strip = (s) => String(s).replace(/[⠀ ]/g, '');
const only = (() => { const i = process.argv.indexOf('--code'); return i >= 0 ? process.argv[i + 1] : null; })();
const CODES = only ? [only] : ['UEB', 'Nemeth'];

const failures = [];
console.log('Curriculum benchmark — the full loop, with the original expression as truth\n');

for (const code of CODES) {
  console.log(`${'='.repeat(70)}\n${code}\n${'='.repeat(70)}`);
  console.log('  stage                        n   readable  consistent  faithful');
  let TN = 0, TR = 0, TC = 0, TF = 0;

  for (const [stage, exprs] of CURRICULUM) {
    let n = 0, readable = 0, consistent = 0, faithful = 0;
    for (const tex of exprs) {
      // the expression as a teacher would write it -> MathML -> braille
      let mathml, braille;
      try { mathml = toMathML(temml, tex); } catch { continue; }
      try { braille = mathcat.mathml_to_braille(mathml, code); } catch { continue; }
      if (typeof braille !== 'string' || !/[⠀-⣿]/.test(braille) || /^ERROR/i.test(braille)) continue;
      n++;

      const r = code === 'UEB' ? uebMathsToLatex(braille) : nemeth(braille);
      const clean = !!(r.latex || '').trim() && !(r.warnings || []).length;
      if (!clean) { failures.push({ code, stage, tex, braille, got: r.latex, why: (r.warnings || [])[0] || 'no output' }); continue; }
      readable++;

      // does our reading regenerate the very braille it came from?
      let back = '';
      try { back = mathcat.mathml_to_braille(toMathML(temml, r.latex), code); } catch { /* */ }
      const isConsistent = typeof back === 'string' && strip(back) === strip(braille);
      if (isConsistent) consistent++;

      if (faithfulness(sourceTokens(mathml), latexTokens(r.latex)).ok) faithful++;
      if (!isConsistent) failures.push({ code, stage, tex, braille, got: r.latex, why: 'reads as something else' });
    }
    const p = (a) => (n ? String(Math.round(a / n * 100)).padStart(3) + '%' : '   —');
    console.log(`  ${stage.padEnd(28)}${String(n).padStart(2)}     ${p(readable)}      ${p(consistent)}     ${p(faithful)}`);
    TN += n; TR += readable; TC += consistent; TF += faithful;
  }
  const P = (a) => (TN ? String(Math.round(a / TN * 100)).padStart(3) + '%' : '   —');
  console.log(`  ${'ALL'.padEnd(28)}${String(TN).padStart(2)}     ${P(TR)}      ${P(TC)}     ${P(TF)}`);

  // the independent set
  let gn = 0, gr = 0, gc = 0, gf = 0;
  for (const tex of GENERATED) {
    let mathml, braille;
    try { mathml = toMathML(temml, tex); } catch { continue; }
    try { braille = mathcat.mathml_to_braille(mathml, code); } catch { continue; }
    if (typeof braille !== 'string' || !/[⠀-⣿]/.test(braille) || /^ERROR/i.test(braille)) continue;
    gn++;
    const r = code === 'UEB' ? uebMathsToLatex(braille) : nemeth(braille);
    if (!(r.latex || '').trim() || (r.warnings || []).length) {
      failures.push({ code, stage: 'independent', tex, braille, got: r.latex, why: (r.warnings || [])[0] || 'no output' });
      continue;
    }
    gr++;
    let back = '';
    try { back = mathcat.mathml_to_braille(toMathML(temml, r.latex), code); } catch { /* */ }
    const ok = typeof back === 'string' && strip(back) === strip(braille);
    if (ok) gc++; else failures.push({ code, stage: 'independent', tex, braille, got: r.latex, why: 'reads as something else' });
    if (faithfulness(sourceTokens(mathml), latexTokens(r.latex)).ok) gf++;
  }
  if (gn) {
    const G = (a) => String(Math.round(a / gn * 100)).padStart(3) + '%';
    console.log(`  ${'INDEPENDENT SET'.padEnd(28)}${String(gn).padStart(2)}     ${G(gr)}      ${G(gc)}     ${G(gf)}`);
  }
  console.log('');
}

if (process.argv.includes('--failures')) {
  console.log('--- what went wrong ---');
  for (const f of failures.slice(0, 40)) {
    console.log(`\n  ${f.code} ${f.stage}`);
    console.log(`    wanted  ${f.tex}`);
    console.log(`    braille ${f.braille}`);
    console.log(`    got     ${JSON.stringify(f.got).slice(0, 70)}`);
    console.log(`    why     ${f.why}`);
  }
}
